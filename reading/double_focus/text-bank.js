function pickText(age, excludeTitles = []){
  const pool = getTextsByAge(age).filter(t => !excludeTitles.includes(t.title));
  const source = pool.length ? pool : getTextsByAge(age);
  return source[Math.floor(Math.random() * source.length)];
}

